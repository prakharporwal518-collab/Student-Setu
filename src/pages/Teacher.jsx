/* ----------------------------------------------------- question paper */
function PaperGenerator({ t, beforeGenerate }) {
  const toast = useToast()
  const [topic, setTopic] = useState('Unit 1: ER model; Unit 2: Relational algebra; Unit 3: Normalization; Unit 4: Transactions; Unit 5: Indexing')
  const [marks, setMarks] = useState('70')
  const [busy, setBusy] = useState(false)
  const [out, setOut] = useState(null)
  const run = async (e) => {
    e.preventDefault()
    if (!beforeGenerate()) return
    setBusy(true)
    try {
      setOut(await generate('paper', { ...t.fields, topic, marks }))
    } catch (err) {
      toast(err.message, 'warning')
    } finally {
      setBusy(false)
    }
  }
  const p = out?.result
  const sum = p?.sections?.reduce((a, s) => a + (s.questions ?? []).reduce((b, q) => b + (+q.marks || 0), 0), 0)
  return (
    <div className="space-y-5">
      <form onSubmit={run} className="card space-y-4 p-5">
        <ContextFields t={t} />
        <div className="grid gap-3 sm:grid-cols-[1fr_160px_auto] sm:items-end">
          <div><label className="label">Units / topics to cover</label><textarea value={topic} onChange={(e) => setTopic(e.target.value)} rows={2} className="input" required /></div>
          <div><label className="label">Total marks</label><Select value={marks} onChange={setMarks} options={['20', '40', '50', '60', '70', '100'].map((m) => ({ value: m, label: `${m} marks` }))} /></div>
          <button className="btn-accent" disabled={busy}>{busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <FileText className="h-4 w-4" />} Generate paper</button>
        </div>
      </form>
      {p && (
        <article className="card print-area space-y-5 p-6">
          <div className="no-print flex flex-wrap items-center justify-between gap-2"><SourceNote out={out} /><button onClick={() => window.print()} className="btn-ghost py-2"><Printer className="h-4 w-4" /> Print</button></div>
          <header className="text-center">
            <p className="text-sm font-semibold">{t.fields.university} · {t.fields.course} · Semester {t.fields.semester}</p>
            <h2 className="text-xl font-extrabold">{p.title}</h2>
            <p className="text-sm text-slate-500">Time: {p.duration} · Maximum marks: {p.totalMarks}{sum && sum !== p.totalMarks ? ` (questions total ${sum} — includes choices)` : ''}</p>
          </header>
          <ul className="list-inside list-disc text-sm text-slate-600 dark:text-slate-300">{p.instructions?.map((i) => <li key={i}>{i}</li>)}</ul>
          {p.sections.map((s) => (
            <section key={s.name}>
              <h3 className="font-bold">{s.name}</h3>
              {s.note && <p className="mb-2 text-xs text-slate-500">{s.note}</p>}
              <ol className="list-inside list-decimal space-y-2 text-sm">
                {s.questions?.map((q, i) => (
                  <li key={i}><span>{q.q}</span> <span className="whitespace-nowrap text-xs text-slate-500">[{q.marks} marks{q.level ? ` · ${q.level}` : ''}]</span></li>
                ))}
              </ol>
            </section>
          ))}
        </article>
      )}
    </div>
  )
}

/* ------------------------------------------------------- quiz builder */
const blankQ = () => ({ q: '', options: ['', '', '', ''], answer: 0, topic: '', explanation: '' })

function QuizBuilder({ t, initialTopic, classes, refreshClasses, onAssigned, canAssign }) {
  const toast = useToast()
  const { user } = useAuth()
  const [title, setTitle] = useState('Unit test')
  const [topic, setTopic] = useState(initialTopic || 'SQL joins and normalization')
  const [count, setCount] = useState('5')
  const [qs, setQs] = useState([])
  const [busy, setBusy] = useState(false)
  const [note, setNote] = useState(null)
  const [target, setTarget] = useState('')
  const [assigned, setAssigned] = useState(null)
  useEffect(() => {
    if (initialTopic) {
      setTopic(initialTopic)
      setTitle(`Quiz: ${initialTopic}`)
    }
  }, [initialTopic])
  useEffect(() => {
    if (!target && classes[0]) setTarget(classes[0].code)
  }, [classes, target])

  const gen = async () => {
    setBusy(true)
    try {
      const out = await generate('quiz', { ...t.fields, topic, count })
      setQs(out.result.questions.map((q) => ({ ...blankQ(), ...q, options: [...q.options] })))
      setNote(out.ai ? null : `${out.note}${out.result.fromBank ? ` Loaded from the “${out.result.fromBank}” question bank — edit as needed.` : ''}`)
    } catch (e) {
      toast(e.message, 'warning')
    } finally {
      setBusy(false)
    }
  }
  const upd = (i, patch) => setQs((list) => list.map((q, j) => (j === i ? { ...q, ...patch } : q)))

  const assign = async () => {
    setBusy(true)
    try {
      let code = target || '__new'
      if (code === '__new') {
        const res = await createClass(user, { subject: t.fields.subject, course: t.fields.course, semester: String(t.fields.semester) })
        code = res.code
        refreshClasses()
        setTarget(code)
      }
      await addQuiz(code, { title, questions: qs.map((q) => ({ ...q, topic: q.topic || topic })) })
      setAssigned(code)
      onAssigned?.(code)
      toast(`Quiz assigned to class ${code}`)
    } catch (e) {
      toast(e.message, 'warning')
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="space-y-5">
      <div className="card space-y-4 p-5">
        <ContextFields t={t} />
        <div className="grid gap-3 sm:grid-cols-[1fr_1fr_120px_auto] sm:items-end">
          <div><label className="label">Quiz title</label><input value={title} onChange={(e) => setTitle(e.target.value)} className="input" /></div>
          <div><label className="label">Topic(s)</label><input value={topic} onChange={(e) => setTopic(e.target.value)} className="input" /></div>
          <div><label className="label">Questions</label><Select value={count} onChange={setCount} options={['3', '5', '8', '10'].map((c) => ({ value: c, label: c }))} /></div>
          <button onClick={gen} disabled={busy || !topic.trim()} className="btn-accent">{busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <Wand2 className="h-4 w-4" />} Generate with AI</button>
        </div>
        {note && <p className="flex items-start gap-1.5 rounded-lg bg-amber-50 p-2 text-xs text-amber-800 dark:bg-amber-500/10 dark:text-amber-200"><Info className="h-4 w-4 shrink-0" /> {note}</p>}
      </div>

      <div className="space-y-3">
        {qs.map((q, i) => (
          <div key={i} className="card space-y-3 p-4">
            <div className="flex items-start gap-2">
              <span className="mt-2 text-sm font-bold text-brand-700">Q{i + 1}</span>
              <textarea value={q.q} onChange={(e) => upd(i, { q: e.target.value })} rows={2} className="input" placeholder="Question text" />
              <button onClick={() => setQs((l) => l.filter((_, j) => j !== i))} className="btn-ghost h-10 w-10 shrink-0 p-0 text-rose-600" aria-label={`Delete question ${i + 1}`}><Trash2 className="h-4 w-4" /></button>
            </div>
            <div className="grid gap-2 sm:grid-cols-2">
              {q.options.map((o, oi) => (
                <label key={oi} className={`flex items-center gap-2 rounded-xl border px-2 ${q.answer === oi ? 'border-emerald-400 bg-emerald-50 dark:bg-emerald-500/10' : 'border-slate-200 dark:border-white/10'}`}>
                  <input type="radio" name={`ans-${i}`} checked={q.answer === oi} onChange={() => upd(i, { answer: oi })} className="accent-emerald-600" aria-label={`Mark option ${oi + 1} correct`} />
                  <input value={o} onChange={(e) => upd(i, { options: q.options.map((x, k) => (k === oi ? e.target.value : x)) })} className="w-full bg-transparent py-2 text-sm outline-none" placeholder={`Option ${oi + 1}`} />
                </label>
              ))}
            </div>
            <div className="grid gap-2 sm:grid-cols-[200px_1fr]">
              <input value={q.topic} onChange={(e) => upd(i, { topic: e.target.value })} className="input py-2" placeholder="Sub-topic (for heatmap)" />
              <input value={q.explanation} onChange={(e) => upd(i, { explanation: e.target.value })} className="input py-2" placeholder="Explanation shown after submitting (optional)" />
            </div>
          </div>
        ))}
        <button onClick={() => setQs((l) => [...l, blankQ()])} className="btn-outline"><Plus className="h-4 w-4" /> Add question manually</button>
      </div>

      {qs.length > 0 && !canAssign && <p className="rounded-xl bg-amber-50 p-3 text-sm text-amber-800 ring-1 ring-amber-200 dark:bg-amber-500/10 dark:text-amber-200">You can build and edit quizzes now. Assigning them to a class unlocks once your teacher profile is verified.</p>}
      {qs.length > 0 && canAssign && (
        <div className="card flex flex-col gap-3 p-5 sm:flex-row sm:items-end">
          <div className="flex-1">
            <label className="label">Assign to class</label>
            <Select value={target || '__new'} onChange={setTarget} options={[...classes.map((c) => ({ value: c.code, label: `${c.subject} — ${c.code}` })), { value: '__new', label: `➕ New class: ${t.fields.subject}` }]} />
          </div>
          <button onClick={assign} disabled={busy} className="btn-primary">{busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <CheckCircle2 className="h-4 w-4" />} Assign quiz ({qs.length} questions)</button>
        </div>
      )}
      {assigned && <ShareClass code={assigned} />}
    </div>
  )
}

