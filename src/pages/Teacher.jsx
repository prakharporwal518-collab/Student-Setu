function Classes({ classes, refreshClasses, selected, setSelected, onReteach }) {
  const toast = useToast()
  const { user } = useAuth()
  const [data, setData] = useState(null)
  const [busy, setBusy] = useState(false)
  const [subject, setSubject] = useState('')
  const [note, setNote] = useState({ title: '', url: '', text: '' })

  const load = async (code) => {
    if (!code) return
    setBusy(true)
    try {
      setData(await getResults(code))
    } catch (e) {
      toast(e.message, 'warning')
      setData(null)
    } finally {
      setBusy(false)
    }
  }
  useEffect(() => {
    load(selected)
  }, [selected]) // eslint-disable-line react-hooks/exhaustive-deps

  const demo = async () => {
    setBusy(true)
    try {
      const r = await createDemoClass(user)
      refreshClasses()
      setSelected(r.code)
      toast('Demo class created with 26 student results')
    } catch (e) {
      toast(e.message, 'warning')
    } finally {
      setBusy(false)
    }
  }
  const create = async (e) => {
    e.preventDefault()
    try {
      const r = await createClass(user, { subject })
      refreshClasses()
      setSelected(r.code)
      setSubject('')
    } catch (err) {
      toast(err.message, 'warning')
    }
  }
  const saveNote = async (e) => {
    e.preventDefault()
    try {
      await addNote(selected, note)
      setNote({ title: '', url: '', text: '' })
      toast('Notes shared with the class')
      load(selected)
    } catch (err) {
      toast(err.message, 'warning')
    }
  }

  const ins = data?.insights
  const avg = ins?.perQuiz.filter((q) => q.avg !== null)
  return (
    <div className="grid gap-5 lg:grid-cols-[280px_1fr]">
      <aside className="space-y-3">
        <button onClick={demo} disabled={busy} className="btn-accent w-full"><Sparkles className="h-4 w-4" /> Try a demo class</button>
        <form onSubmit={create} className="card space-y-2 p-4">
          <label className="label">New class (subject)</label>
          <input value={subject} onChange={(e) => setSubject(e.target.value)} className="input" placeholder="e.g. DBMS — Section A" required />
          <button className="btn-primary w-full py-2"><Plus className="h-4 w-4" /> Create class</button>
        </form>
        <div className="card divide-y divide-slate-100 dark:divide-white/10">
          {classes.length === 0 && <p className="p-4 text-sm text-slate-500">No classes yet.</p>}
          {classes.map((c) => (
            <button key={c.code} onClick={() => setSelected(c.code)} className={`flex w-full items-center justify-between gap-2 p-3 text-left ${selected === c.code ? 'bg-brand-50 dark:bg-white/10' : ''}`}>
              <span className="min-w-0"><span className="block truncate text-sm font-semibold">{c.subject}</span><span className="font-mono text-xs text-slate-500">{c.code}{c.demo ? ' · demo' : ''}</span></span>
              <Badge tone={c.mode === 'online' ? 'green' : 'gray'}>{c.mode === 'online' ? 'Online' : 'This device'}</Badge>
            </button>
          ))}
        </div>
      </aside>

      <div className="min-w-0 space-y-5">
        {!selected && <EmptyState icon={BarChart3} title="Pick or create a class" text="Try the demo class to see the weak-topic heatmap with 26 student results." />}
        {busy && selected && <p className="flex items-center gap-2 text-sm text-slate-500"><Loader2 className="h-4 w-4 animate-spin" /> Loading class…</p>}
        {data && (
          <>
            <ShareClass code={data.class.code} />
            <div className="grid grid-cols-3 gap-3">
              <div className="card p-4 text-center"><p className="font-display text-2xl font-extrabold">{ins.students.length}</p><p className="text-xs text-slate-500">Submissions</p></div>
              <div className="card p-4 text-center"><p className="font-display text-2xl font-extrabold">{avg?.length ? Math.round(avg.reduce((a, q) => a + q.avg, 0) / avg.length) : '—'}%</p><p className="text-xs text-slate-500">Average score</p></div>
              <div className="card p-4 text-center"><p className="font-display text-2xl font-extrabold">{data.class.quizzes.length}</p><p className="text-xs text-slate-500">Quizzes</p></div>
            </div>

            <div className="card p-5">
              <h3 className="mb-1 flex items-center gap-2 font-bold"><BarChart3 className="h-5 w-5 text-brand-700" /> Weak-topic heatmap</h3>
              <p className="mb-4 text-sm text-slate-500">Share of correct answers per topic across all quizzes.</p>
              {ins.topics.length === 0 ? (
                <p className="text-sm text-slate-500">No results yet — share the class code and assign a quiz.</p>
              ) : (
                <div className="grid grid-cols-2 gap-2 sm:grid-cols-3 lg:grid-cols-5">
                  {ins.topics.map((tp) => (
                    <div key={tp.topic} className={`rounded-xl p-3 ${heat(tp.pct)}`}>
                      <p className="text-xs font-semibold opacity-90">{tp.topic}</p>
                      <p className="font-display text-2xl font-extrabold">{tp.pct === null ? '—' : `${tp.pct}%`}</p>
                      <p className="text-[11px] opacity-80">{tp.attempts} answers</p>
                    </div>
                  ))}
                </div>
              )}
              {ins.weakest && (
                <div className="mt-4 flex flex-wrap items-center gap-3 rounded-xl bg-rose-50 p-3 text-sm text-rose-800 ring-1 ring-rose-200 dark:bg-rose-500/10 dark:text-rose-200 dark:ring-rose-400/20">
                  <span className="flex-1">Only <b>{ins.weakest.pct}%</b> of answers on <b>{ins.weakest.topic}</b> were correct. Re-teach it before moving on.</span>
                  <button onClick={() => onReteach(ins.weakest.topic)} className="btn-primary py-2"><NotebookPen className="h-4 w-4" /> Plan a re-teach lesson</button>
                </div>
              )}
            </div>

            {ins.perQuiz.map((qz) => (
              <div key={qz.id} className="card p-5">
                <div className="mb-3 flex items-center justify-between gap-2"><h3 className="font-bold">{qz.title}</h3><span className="text-sm text-slate-500">{qz.submissions} submissions{qz.avg !== null ? ` · avg ${qz.avg}%` : ''}</span></div>
                <ul className="space-y-2">
                  {qz.questions.map((q, i) => (
                    <li key={i} className="text-sm">
                      <div className="flex justify-between gap-2"><span className="truncate">Q{i + 1}. {q.q}</span><span className="shrink-0 font-semibold">{q.pct === null ? '—' : `${q.pct}%`}</span></div>
                      <div className="mt-1 h-2 overflow-hidden rounded-full bg-slate-100 dark:bg-white/10"><div className={`h-full ${heat(q.pct)}`} style={{ width: `${q.pct ?? 0}%` }} /></div>
                    </li>
                  ))}
                </ul>
              </div>
            ))}

            {ins.students.length > 0 && (
              <div className="card overflow-x-auto">
                <table className="w-full min-w-[420px] text-left text-sm">
                  <thead className="border-b border-slate-100 text-xs uppercase text-slate-400 dark:border-white/10"><tr><th className="p-3">Student</th><th className="p-3">Quiz</th><th className="p-3">Score</th></tr></thead>
                  <tbody>{ins.students.slice(0, 30).map((s, i) => <tr key={i} className="border-b border-slate-50 last:border-0 dark:border-white/5"><td className="p-3 font-medium">{s.name}</td><td className="p-3 text-slate-500">{s.quiz}</td><td className="p-3"><Badge tone={s.score / s.total >= 0.6 ? 'green' : 'red'}>{s.score}/{s.total}</Badge></td></tr>)}</tbody>
                </table>
              </div>
            )}

            <div className="card p-5">
              <h3 className="mb-3 flex items-center gap-2 font-bold"><BookOpenCheck className="h-5 w-5 text-emerald-600" /> Share notes once, reach every student</h3>
              <form onSubmit={saveNote} className="grid gap-2 sm:grid-cols-2">
                <input value={note.title} onChange={(e) => setNote({ ...note, title: e.target.value })} className="input" placeholder="Title, e.g. Unit 4 notes" required />
                <input value={note.url} onChange={(e) => setNote({ ...note, url: e.target.value })} className="input" placeholder="Link to PDF / Drive / video (optional)" type="url" />
                <textarea value={note.text} onChange={(e) => setNote({ ...note, text: e.target.value })} className="input sm:col-span-2" rows={2} placeholder="Short message or summary (students can listen to it offline)" />
                <button className="btn-primary sm:col-span-2 sm:w-fit"><Plus className="h-4 w-4" /> Share with class</button>
              </form>
              <ul className="mt-4 space-y-2">{data.class.notes.map((n) => <li key={n.id} className="rounded-xl bg-slate-50 p-3 text-sm dark:bg-white/5"><p className="font-semibold">{n.title}</p>{n.text && <p className="text-slate-600 dark:text-slate-300">{n.text}</p>}{n.url && <a href={n.url} target="_blank" rel="noreferrer" className="link text-xs">Open link ↗</a>}</li>)}</ul>
            </div>
            <button onClick={() => { forgetClass(data.class.code); refreshClasses(); setSelected(''); setData(null) }} className="text-xs text-slate-400 hover:text-rose-600">Remove this class from my list</button>
          </>
        )}
      </div>
    </div>
  )
}

