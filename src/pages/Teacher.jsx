/* ---------------------------------------------------- shared context form */
function useTeachingContext() {
  const [ctx, setCtx] = useState({ courseId: 'btech', uni: 'rgpv', sem: 5, subject: 'Database Management Systems', language: 'en' })
  const course = courses.find((c) => c.id === ctx.courseId)
  const subjects = course.semesters[ctx.sem] ?? []
  const set = (patch) =>
    setCtx((c) => {
      const next = { ...c, ...patch }
      const co = courses.find((x) => x.id === next.courseId)
      if (!co.universities.includes(next.uni)) next.uni = co.universities[0]
      if (next.sem > co.years * 2) next.sem = 1
      const subs = co.semesters[next.sem] ?? []
      if (!subs.includes(next.subject)) next.subject = subs[0]
      return next
    })
  const fields = { course: course.name, university: collegeById(ctx.uni)?.short, semester: ctx.sem, subject: ctx.subject, language: ctx.language }
  return { ctx, set, course, subjects, fields }
}

function ContextFields({ t }) {
  const { ctx, set, course, subjects } = t
  return (
    <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
      <div><label className="label">Course</label><Select value={ctx.courseId} onChange={(v) => set({ courseId: v })} options={courses.map((c) => ({ value: c.id, label: c.name }))} /></div>
      <div><label className="label">University</label><Select value={ctx.uni} onChange={(v) => set({ uni: v })} options={course.universities.map((u) => ({ value: u, label: collegeById(u)?.short ?? u }))} /></div>
      <div><label className="label">Semester</label><Select value={String(ctx.sem)} onChange={(v) => set({ sem: +v })} options={Array.from({ length: course.years * 2 }, (_, i) => ({ value: String(i + 1), label: `Semester ${i + 1}` }))} /></div>
      <div><label className="label">Subject</label><Select value={ctx.subject} onChange={(v) => set({ subject: v })} options={subjects.map((s) => ({ value: s, label: s }))} /></div>
      <div>
        <label className="label">Language</label>
        <div className="flex rounded-xl bg-slate-100 p-1 dark:bg-white/10">
          {[['en', 'English'], ['hi', 'हिंदी']].map(([v, l]) => (
            <button key={v} type="button" onClick={() => set({ language: v })} className={`flex-1 rounded-lg py-1.5 text-sm font-semibold ${ctx.language === v ? 'bg-white shadow dark:bg-ink-900' : 'text-slate-500'}`}>{l}</button>
          ))}
        </div>
      </div>
    </div>
  )
}

function SourceNote({ out }) {
  if (!out) return null
  return out.ai ? (
    <Badge tone="purple"><Sparkles className="h-3 w-3" /> Generated by Gemini — review before use</Badge>
  ) : (
    <p className="flex items-start gap-1.5 rounded-lg bg-amber-50 p-2 text-xs text-amber-800 dark:bg-amber-500/10 dark:text-amber-200"><Info className="h-4 w-4 shrink-0" /> {out.note}</p>
  )
}

